#!/usr/bin/env python3
"""
update_example_slides.py

Replace slide 18 ("Example Plots - MLP Prediction") with 3 separate slides,
one per session-ensemble-trial trio.  Each slide shows only the all-models
overlay plot.

Trios generated by eval_spikes_and_traces.py:
  S01_E03  Session 2024-11-14_16-40  Ensemble E03  Trial 22
  S07_E04  Session 2024-11-28_17-41  Ensemble E04  Trial 2
  S25_E05  Session 2025-01-24_12-24  Ensemble E05  Trial 31

Run standalone on Neural_Task_Representation_cleanup.pptx (before or after
update_cleanup_slides.py — this script owns slide 18 and the two it inserts).
"""
import os
import copy
from pptx import Presentation
from pptx.util import Emu

PPTX_PATH = "/mnt/c/Users/amits/Downloads/Neural_Task_Representation_cleanup.pptx"
base   = os.path.dirname(os.path.abspath(__file__))
root   = os.path.join(base, "..")
traces = os.path.join(root, "outputs", "trial_traces_comparison")

TRIOS = [
    "overlay_S01_E03.png",
    "overlay_S07_E04.png",
    "overlay_S25_E05.png",
]

# Overlay image geometry: full slide width, vertically centred in content area.
# Original matplotlib figsize=(14, 4) → aspect ratio 3.5:1.
# Slide width = 9 144 000 EMU → maintain ratio: height = 9144000 / 3.5
IMG_L = Emu(0)
IMG_W = Emu(9_144_000)
IMG_H = Emu(round(9_144_000 / 3.5))           # ≈ 2 612 571 EMU
# Centre between title bottom (~1 053 478) and slide bottom (~5 143 500)
_content_mid = (1_053_478 + 5_143_500) // 2
IMG_T = Emu(_content_mid - IMG_H // 2)


def _remove_all_pictures(slide):
    for pic in [s for s in slide.shapes if s.shape_type == 13]:
        pic._element.getparent().remove(pic._element)


def _add_overlay(slide, fname):
    img_path = os.path.join(traces, fname)
    if not os.path.exists(img_path):
        print(f"  SKIP (missing): {img_path}")
        return
    slide.shapes.add_picture(img_path, IMG_L, IMG_T, width=IMG_W, height=IMG_H)
    print(f"  added {fname}")


def insert_slide_after(prs, after_idx, layout):
    """Add a new slide using layout, then move it to position after_idx+1."""
    new_slide = prs.slides.add_slide(layout)
    sld_id_lst = prs.slides._sldIdLst
    new_elem   = sld_id_lst[-1]           # just appended
    sld_id_lst.remove(new_elem)
    sld_id_lst.insert(after_idx + 1, new_elem)
    return new_slide


prs    = Presentation(PPTX_PATH)
slides = prs.slides

# ── Slide 18 (idx 17): replace images with first trio overlay ─────────────────
print("S18:")
s18 = slides[17]
_remove_all_pictures(s18)
_add_overlay(s18, TRIOS[0])

# ── Insert 2 new slides after idx 17 for the remaining trios ─────────────────
layout = s18.slide_layout
title_text = next(
    (s.text.strip() for s in s18.shapes if s.shape_type == 14
     and s.placeholder_format is not None and s.placeholder_format.idx == 0),
    "Example Plots - MLP Prediction",
)

for i, fname in enumerate(TRIOS[1:], start=1):
    new_slide = insert_slide_after(prs, 17 + i - 1, layout)
    # Set title to match slide 18
    for ph in new_slide.placeholders:
        if ph.placeholder_format.idx == 0:
            ph.text = title_text
            break
    print(f"S{18 + i} (inserted):")
    _add_overlay(new_slide, fname)

prs.save(PPTX_PATH)
print(f"\nSaved → {PPTX_PATH}")
print("NOTE: slides after the original S18 are now shifted by +2.")
print("      Re-run update_cleanup_slides.py if you need to refresh other slides.")
